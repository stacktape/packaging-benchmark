/** Turns results/results.json into results/RESULTS.md. Plain tables, no interpretation. */

import { writeFileSync } from 'node:fs';

type Any = Record<string, any>;
type ConfigLike = 'likeforlike' | 'defaults';

const kb = (bytes: number | null | undefined) =>
  bytes === null || bytes === undefined ? '-' : `${(bytes / 1024).toFixed(1)} KB`;

const mb = (bytes: number | null | undefined) =>
  bytes === null || bytes === undefined ? '-' : `${(bytes / (1024 * 1024)).toFixed(1)} MB`;

const gb = (bytes: number | null | undefined) =>
  bytes === null || bytes === undefined ? '-' : `${(bytes / 1024 ** 3).toFixed(1)} GB`;

const secs = (ms: number | null | undefined) =>
  ms === null || ms === undefined ? '-' : `${(ms / 1000).toFixed(2)} s`;

const median = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? (sorted[mid - 1] + sorted[mid]) / 2 : sorted[mid];
};

const table = (headers: string[], rows: (string | number)[][]) =>
  [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`)
  ].join('\n');

const SHAPE_ORDER = ['n1', 'n5', 'n10', 'n25', 'n50', 'noshare25', 'mono10'];

const shapeLabel: Record<string, string> = {
  n1: 'S1/S2 - 1 function',
  n5: 'S2 - 5 functions',
  n10: 'S2 - 10 functions',
  n25: 'S2 - 25 functions',
  n50: 'S2 - 50 functions',
  noshare25: 'S3 - 25 functions, shares nothing',
  mono10: 'S4 - pnpm monorepo, 10 functions'
};

export const writeReport = (results: Any, path: string) => {
  const lines: string[] = [];
  const lambda: Any[] = results.lambda ?? [];
  const tools = [...new Set(lambda.map((m) => m.tool))];

  lines.push('# Results', '');
  lines.push(
    'Generated by `node bench/run.ts report` from `results/results.json`. Every number here is a ' +
      'measurement from one machine; see the environment block below and the caveats in the repository ' +
      'README before quoting any of it.',
    ''
  );

  // --- environment ---------------------------------------------------------
  const env = results.environment as Any | null;
  if (env) {
    lines.push('## Environment', '');
    lines.push(
      table(
        ['Item', 'Value'],
        [
          ['Captured', env.capturedAt],
          ['CPU', `${env.cpu.model} (${env.cpu.logicalCores} logical cores)`],
          ['RAM', gb(env.memoryBytes)],
          ['OS', `${env.os.distribution ?? env.os.type} - kernel ${env.os.release}${env.os.wsl ? ' (WSL2)' : ''}`],
          ['Node', env.runtimes.node],
          ['Bun', env.runtimes.bun ?? '-'],
          ['pnpm', env.runtimes.pnpm ?? '-'],
          ['npm', env.runtimes.npm ?? '-'],
          ['Docker', env.runtimes.docker ?? '-'],
          ...Object.entries(env.toolVersions ?? {}).map(([k, v]) => [k, String(v)]),
          [
            'Stacktape CLI',
            env.stacktape
              ? `source build at ${String(env.stacktape.commit).slice(0, 12)} (+${env.stacktape.dirtyFiles} uncommitted files)`
              : 'not available'
          ]
        ]
      ),
      ''
    );
  }

  // --- blocked -------------------------------------------------------------
  if ((results.blocked ?? []).length > 0) {
    lines.push('## Tools that could not be measured', '');
    for (const blocked of results.blocked as Any[]) {
      lines.push(`- **${blocked.tool}** - ${blocked.reason}`, '');
    }
  }

  // --- package time --------------------------------------------------------
  for (const config of ['likeforlike', 'defaults'] as const) {
    const heading = config === 'likeforlike' ? 'like-for-like' : 'defaults';
    lines.push(`## Package time - ${heading} configuration`, '');
    lines.push(
      'Wall clock of the tool\'s package/synth command, median of the recorded samples. ' +
        '"Cold" deletes the tool\'s output and cache directories first; "warm" runs again immediately ' +
        'with no change.',
      ''
    );
    const headers = ['Shape', 'Functions', ...tools.flatMap((t) => [`${t} cold`, `${t} warm`])];
    const rows = SHAPE_ORDER.filter((shape) => lambda.some((m) => m.shape === shape)).map((shape) => {
      const any = lambda.find((m) => m.shape === shape)!;
      return [
        shapeLabel[shape] ?? shape,
        any.functions,
        ...tools.flatMap((tool) => {
          const cold = lambda.find((m) => m.shape === shape && m.tool === tool && m.config === config && m.mode === 'cold');
          const warm = lambda.find((m) => m.shape === shape && m.tool === tool && m.config === config && m.mode === 'warm');
          return [cold?.ok ? secs(cold.medianMs) : '-', warm?.ok ? secs(warm.medianMs) : '-'];
        })
      ];
    });
    lines.push(table(headers, rows), '');
  }

  // --- where Stacktape's wall clock goes ------------------------------------
  const overheadMs = (results.overhead as Any)?.medianMs as number | undefined;
  const selfReported = lambda.filter((m) => m.ok && m.toolReportedMs !== null);
  if (overheadMs && selfReported.length > 0) {
    lines.push('## Where the Stacktape wall clock goes', '');
    lines.push(
      `Starting the CLI binary and printing its version takes ${secs(overheadMs)} (median, measured ` +
        'separately; samples below). That is the floor under every Stacktape row in the tables above: it is ' +
        'process start-up only, before any configuration is read, any AWS call is made or any packaging ' +
        'happens.',
      ''
    );
    lines.push(
      'The CLI also prints the duration of its own packaging phase. That figure excludes process start-up, ' +
        'configuration loading and the AWS identity lookup, so it is not comparable with any other tool here ' +
        '- no other tool prints an equivalent - but it does separate the packaging work from everything ' +
        'around it. Only the packaging phase grows with the number of functions.',
      ''
    );
    lines.push(
      'The last two columns do not add up to the first. The gap is configuration loading and the AWS ' +
        'identity lookup, which no column isolates, plus a run-to-run spread of a few hundred milliseconds ' +
        'on this machine. No adjusted package time is offered: every tool here pays its own start-up, and ' +
        'subtracting only Stacktape\'s would not make the comparison fairer.',
      ''
    );
    const rows: (string | number)[][] = [];
    for (const shape of SHAPE_ORDER) {
      for (const config of ['likeforlike', 'defaults'] as ConfigLike[]) {
        const m = lambda.find(
          (x) => x.shape === shape && x.tool === 'stacktape' && x.config === config && x.mode === 'cold' && x.ok
        );
        if (!m) continue;
        rows.push([
          shapeLabel[shape] ?? shape,
          config,
          secs(m.medianMs),
          secs(overheadMs),
          m.toolReportedMs ? secs(m.toolReportedMs) : '-'
        ]);
      }
    }
    lines.push(
      table(
        [
          'Shape',
          'Configuration',
          'Measured wall clock (cold, median)',
          'CLI start-up (constant)',
          'Packaging phase as the CLI reports it'
        ],
        rows
      ),
      ''
    );
  }

  // --- size ----------------------------------------------------------------
  for (const config of ['likeforlike', 'defaults'] as const) {
    const heading = config === 'likeforlike' ? 'like-for-like' : 'defaults';
    lines.push(`## Artifact size - ${heading} configuration`, '');
    lines.push(
      '"Upload on first deploy" is the sum of the distinct artifacts a first deployment has to send: ' +
        'every function bundle plus every shared layer, counted once. Zipped bytes are computed the same ' +
        'way for every tool (see the README).',
      ''
    );
    const headers = [
      'Shape',
      'Tool',
      'Functions',
      'Code artifacts',
      'Layers',
      'Function code unzipped',
      'Layers unzipped',
      'Upload on first deploy (zipped)'
    ];
    const rows: (string | number)[][] = [];
    for (const shape of SHAPE_ORDER) {
      for (const tool of tools) {
        const m = lambda.find(
          (x) => x.shape === shape && x.tool === tool && x.config === config && x.mode === 'cold' && x.ok
        );
        if (!m?.totals) continue;
        rows.push([
          shapeLabel[shape] ?? shape,
          tool,
          m.totals.functionCount,
          m.totals.artifactCount ?? m.totals.functionCount,
          m.totals.layerCount,
          kb(m.totals.functionUnzippedBytes),
          kb(m.totals.layerUnzippedBytes),
          kb(m.totals.firstDeployUploadZippedBytes)
        ]);
      }
    }
    lines.push(table(headers, rows), '');
  }

  // --- footprint -----------------------------------------------------------
  lines.push('## S6 - cold-start footprint proxy', '');
  lines.push(
    'Unzipped bytes Lambda would load at cold start for one function: its own artifact plus every layer ' +
      'attached to it. For per-function bundlers that is the bundle alone. This is a proxy - real ' +
      'cold-start latency needs deployments and is out of scope here.',
    ''
  );
  const footprintRows: (string | number)[][] = [];
  for (const shape of ['n25', 'n50']) {
    for (const tool of tools) {
      for (const config of ['likeforlike', 'defaults'] as const) {
        const m = lambda.find(
          (x) => x.shape === shape && x.tool === tool && x.config === config && x.mode === 'cold' && x.ok
        );
        if (!m?.footprint) continue;
        footprintRows.push([
          shapeLabel[shape] ?? shape,
          tool,
          config,
          kb(m.footprint.medianBytes),
          kb(m.footprint.maxBytes)
        ]);
      }
    }
  }
  lines.push(table(['Shape', 'Tool', 'Configuration', 'Median per function', 'Largest'], footprintRows), '');

  // --- incremental ---------------------------------------------------------
  lines.push('## S5 - incremental packaging (25 functions, like-for-like)', '');
  lines.push(
    'Package once, append one statement, package again, then package a third time with nothing further ' +
      'changed. Two scenarios: a change to one handler, and a change to a file in `lib/` that every handler ' +
      'imports. Artifacts are compared by the hash of their contents, not by the zip bytes, which carry ' +
      'timestamps. Times are medians over the recorded repeats.',
    ''
  );
  lines.push(
    'Every tool here skips uploading an artifact whose hash is unchanged - CDK by asset hash, SST by Pulumi ' +
      'asset hash, Stacktape by its own digest. Serverless Framework re-uploads every function artifact on ' +
      'every deployment regardless of whether it changed.',
    ''
  );
  const incRows = ((results.incremental ?? []) as Any[]).map((row) => [
    row.tool,
    row.scenarioLabel ?? row.scenario ?? '-',
    secs(row.runs.first),
    secs(row.runs.afterOneLineChange),
    secs(row.runs.unchanged),
    `${row.changedByOneLineChange.changedCount} / ${row.changedByOneLineChange.totalCount}`,
    kb(row.changedByOneLineChange.changedZippedBytes),
    `${row.changedByNoChange.changedCount} / ${row.changedByNoChange.totalCount}`
  ]);
  lines.push(
    table(
      [
        'Tool',
        'Change',
        'Run 1',
        'Run 2 (after the change)',
        'Run 3 (nothing changed since run 2)',
        'Artifacts re-hashed by the change',
        'Bytes that would be re-uploaded',
        'Artifacts re-hashed by no change'
      ],
      incRows
    ),
    ''
  );
  for (const row of (results.incremental ?? []) as Any[]) {
    const names = row.changedByOneLineChange.changedNames as string[];
    if (names.length > 0 && names.length <= 6) {
      lines.push(`- ${row.tool}, ${row.scenario}: re-hashed ${names.join(', ')}.`);
    } else if (names.length > 6) {
      lines.push(
        `- ${row.tool}, ${row.scenario}: re-hashed ${names.length} artifacts, including ${names.slice(0, 4).join(', ')}.`
      );
    }
    if (row.changedByNoChange.changedCount > 0) {
      lines.push(
        `- ${row.tool}, ${row.scenario}: **${row.changedByNoChange.changedCount} artifact(s) re-hashed with no ` +
          'source change at all**, which means a redeploy would re-upload them for nothing.'
      );
    }
  }
  lines.push('');

  // --- overhead ------------------------------------------------------------
  if (results.overhead?.medianMs) {
    lines.push('## Stacktape CLI start-up', '');
    lines.push(results.overhead.what, '');
    lines.push(
      table(
        ['Measurement', 'Value'],
        [
          ['Median', secs(results.overhead.medianMs)],
          ['Samples (ms)', (results.overhead.samples as number[]).join(', ')]
        ]
      ),
      ''
    );
  }

  // --- SST -----------------------------------------------------------------
  const sst = results.sst as Any | null;
  if (sst?.measurements?.length) {
    lines.push('## SST, measured through a deployed stage', '');
    lines.push(
      'SST cannot be measured like the other tools. It has no packaging command, and on a stage that does ' +
        'not exist yet its preview never builds the bundles. The only way to get numbers is to deploy a ' +
        'stage first. Each shape was deployed into its own throwaway stage of app `pkgbench`, measured, and ' +
        'removed before the next shape started.',
      ''
    );
    lines.push(
      '**What the timed command includes.** `sst diff --stage <stage>` rebuilds every function bundle and ' +
        'then runs a Pulumi preview against the deployed state. The preview contacts AWS. This is therefore ' +
        'not a pure package step, and the number is not comparable with `cdk synth`, `stacktape package` or ' +
        '`serverless package`, all of which do local work only. It is reported because it is the closest ' +
        'analogue SST has, not because it measures the same thing.',
      ''
    );
    const sstRows = (sst.measurements as Any[]).map((m) => {
      const artifacts = (m.artifacts ?? []) as Any[];
      const unzipped = artifacts.reduce((s, a) => s + a.unzippedBytes, 0);
      const distinct = new Map(artifacts.map((a) => [a.contentHash, a]));
      const upload = [...distinct.values()].reduce((s, a) => s + a.zippedBytes, 0);
      const perFunction = artifacts.map((a) => a.unzippedBytes);
      return [
        shapeLabel[m.shape] ?? m.shape,
        m.config,
        m.ok ? secs(m.medianMs) : 'failed',
        secs(m.deployMs),
        m.artifactsFound ?? artifacts.length,
        artifacts.length ? kb(unzipped) : '-',
        artifacts.length ? kb(upload) : '-',
        perFunction.length ? kb(median(perFunction)) : '-'
      ];
    });
    lines.push(
      table(
        [
          'Shape',
          'Configuration',
          '`sst diff` (median)',
          'First deploy of the stage',
          'Artifacts found',
          'Functions unzipped',
          'Upload on first deploy (zipped)',
          'Footprint per function'
        ],
        sstRows
      ),
      ''
    );
  }

  // --- AWS resources -------------------------------------------------------
  if (sst?.resourceLog?.length) {
    lines.push('## AWS resources this benchmark created and removed', '');
    lines.push(
      'Only the SST measurements touch AWS with anything other than a read. Every stage below was removed ' +
        'before the next shape was deployed.',
      ''
    );
    lines.push(
      table(
        ['Action', 'What', 'Detail'],
        (sst.resourceLog as Any[]).map((entry) => [
          entry.action,
          entry.what,
          String(entry.detail ?? '').slice(0, 160).replace(/\n/g, ' ')
        ])
      ),
      ''
    );

    const footprint = sst.accountFootprint as Any | undefined;
    if (footprint) {
      lines.push(`### Outside the per-stage lifecycle (account ${footprint.account}, ${footprint.region})`, '');
      lines.push(footprint.note, '');
      lines.push('**Created**', '');
      for (const item of footprint.created as Any[]) {
        lines.push(`- ${item.resource} — ${item.by}, ${item.at}`);
      }
      lines.push('', '**Removed by hand after the last shape**', '');
      for (const item of footprint.removed as Any[]) lines.push(`- ${item.resource} — ${item.how}`);
      lines.push('', '**Deliberately left alone**', '');
      for (const item of footprint.leftAlone as string[]) lines.push(`- ${item}`);
      lines.push('', '**Verified absent afterwards**', '');
      for (const item of footprint.verifiedAfterCleanup as string[]) lines.push(`- ${item}`);
      lines.push('');
    }
  }

  // --- containers ----------------------------------------------------------
  lines.push('## Containers', '');
  lines.push(
    'The same application as a long-running HTTP service. Image size is `docker image inspect ' +
      "--format '{{.Size}}'`, the uncompressed image size. (On Docker 29 with the containerd image store, " +
      '`docker image ls` prints a different, larger figure for the same image - it is not the number used ' +
      'here.) Cold build prunes the build cache and passes `--no-cache`; warm rebuild changes one line of ' +
      '`src/server.ts` and builds again with the cache on. Base images were pulled before any timing.',
    ''
  );
  const containerRows = ((results.containers ?? []) as Any[])
    .filter((row) => row.variant)
    .map((row) => [
      row.label ?? row.variant,
      row.baseImage ?? '-',
      row.imageSizeBytes ? mb(row.imageSizeBytes) : '-',
      secs(row.coldBuildMs),
      secs(row.warmRebuildMs),
      row.ok ? 'ok' : `failed: ${String(row.error ?? '').slice(0, 120)}`
    ]);
  lines.push(
    table(
      ['Variant', 'Runtime base', 'Image size', 'Cold build (no cache)', 'Warm rebuild (one line changed)', 'Status'],
      containerRows
    ),
    ''
  );

  // --- raw samples ---------------------------------------------------------
  lines.push('## Every sample', '');
  lines.push(
    table(
      ['Shape', 'Tool', 'Configuration', 'Mode', 'Samples (ms)', 'Median', 'Tool-reported'],
      lambda
        .filter((m) => m.ok)
        .map((m) => [
          m.shape,
          m.tool,
          m.config,
          m.mode,
          m.samples.join(', '),
          secs(m.medianMs),
          m.toolReportedMs ? secs(m.toolReportedMs) : '-'
        ])
    ),
    ''
  );

  const failures = lambda.filter((m) => !m.ok);
  if (failures.length > 0) {
    lines.push('## Failed measurements', '');
    for (const failure of failures) {
      lines.push(`- \`${failure.shape}/${failure.tool}/${failure.config}/${failure.mode}\`: ${failure.error}`);
    }
    lines.push('');
  }

  writeFileSync(path, `${lines.join('\n')}\n`);
};
